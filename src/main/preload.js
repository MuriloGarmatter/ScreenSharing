'use strict';

const { contextBridge, ipcRenderer } = require('electron');

// API mínima exposta à interface (a página não tem acesso ao Node).
contextBridge.exposeInMainWorld('telao', {
  appInfo: () => ipcRenderer.invoke('app:info'),
  listSources: (options) => ipcRenderer.invoke('sources:list', {
    thumbnails: options?.thumbnails !== false,
    windowThumbnails: options?.windowThumbnails === true,
  }),
  selectSource: (sourceId, withAudio) => ipcRenderer.invoke('sources:select', sourceId, withAudio),
  startServer: (options) => ipcRenderer.invoke('server:start', options),
  stopServer: () => ipcRenderer.invoke('server:stop'),
  startTunnel: () => ipcRenderer.invoke('tunnel:start'),
  downloadCloudflared: () => ipcRenderer.invoke('tunnel:download'),
  onTunnelProgress: (callback) => ipcRenderer.on('tunnel:progress', (_event, fraction) => callback(fraction)),
  onTunnelClosed: (callback) => ipcRenderer.on('tunnel:closed', () => callback()),
  startAppAudio: (options) => ipcRenderer.invoke('appaudio:start', options),
  stopAppAudio: (session) => ipcRenderer.invoke('appaudio:stop', session),
  listAudioApps: () => ipcRenderer.invoke('appaudio:list'),
  takePendingInvite: () => ipcRenderer.invoke('invite:pending'),
  onInvite: (callback) => ipcRenderer.on('invite:open', (_event, link) => callback(link)),
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  setStatus: (status) => ipcRenderer.invoke('status:set', status),
  onCommand: (callback) => ipcRenderer.on('command', (_event, command) => callback(command)),
  attention: (options) => ipcRenderer.invoke('attention', options),
  showWindow: () => ipcRenderer.invoke('window:show'),
  onAppAudioData: (callback) => ipcRenderer.on('appaudio:data', (_event, session, id, payload) => callback(session, id, payload)),
  onAppAudioEvent: (callback) => ipcRenderer.on('appaudio:event', (_event, session, data) => callback(session, data)),
  ps5List: () => ipcRenderer.invoke('ps5:list'),
  ps5Discover: (options) => ipcRenderer.invoke('ps5:discover', options),
  ps5Register: (options) => ipcRenderer.invoke('ps5:register', options),
  ps5Forget: (id) => ipcRenderer.invoke('ps5:forget', id),
  ps5Start: (options) => ipcRenderer.invoke('ps5:start', options),
  ps5Keyframe: (session) => ipcRenderer.invoke('ps5:keyframe', session),
  ps5Stop: (session) => ipcRenderer.invoke('ps5:stop', session),
  ps5Login: () => ipcRenderer.invoke('ps5:login'),
  ps5OpenLog: () => ipcRenderer.invoke('ps5:open-log'),
  onPs5Video: (callback) => ipcRenderer.on('ps5:video', (_event, session, id, payload) => callback(session, id, payload)),
  onPs5Audio: (callback) => ipcRenderer.on('ps5:audio', (_event, session, payload) => callback(session, payload)),
  onPs5Event: (callback) => ipcRenderer.on('ps5:event', (_event, session, data) => callback(session, data)),
  setAppearance: (options) => ipcRenderer.invoke('appearance:set', options),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  keepAwake: (on) => ipcRenderer.invoke('power:keep-awake', on === true),
  getUpdateStatus: () => ipcRenderer.invoke('update:status'),
  onUpdateStatus: (callback) => ipcRenderer.on('update:status', (_event, status) => callback(status)),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  quitApp: () => ipcRenderer.invoke('app:quit'),
});
